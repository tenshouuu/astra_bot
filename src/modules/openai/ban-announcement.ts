import OpenAI from "openai";
import type { AppConfig } from "@app/config/env";
import type { ResponsesClient } from "@app/modules/openai/api";
import { characterInstructions } from "@app/modules/openai/character";

export function createBanAnnouncement(
  config: Pick<AppConfig, "openaiApiKey" | "openaiModel">,
  client: ResponsesClient = new OpenAI({ apiKey: config.openaiApiKey, maxRetries: 0 }),
): () => Promise<string> {
  let active = 0;
  return async () => {
    if (active >= 2) throw new Error("Ban announcement capacity reached");
    active++;
    try {
      const response = await client.responses.create(
        {
          model: config.openaiModel,
          instructions: `${characterInstructions}
Сейчас ты пишешь короткую реплику в группу после уже выполненного действия.
Достоверный факт: владелец подтвердил постоянный бан одного участника,
Telegram подтвердил бан этого участника в этой группе.
Удаление сообщений здесь не подтверждено: не говори, что сообщения удалены или чат очищен.
Напиши по-русски одну короткую реплику, обычно 5–15 слов, не более 300 символов.
Это лёгкая реплика после завершённой модерации, а не предупреждение или спор:
здесь уместны юмор, самоирония и немного довольной дерзости в стиле Астры.
Создай весёлое, лёгкое настроение: шути про свою маленькую выполненную работу и довольство собой.
Не делай бан или наказание центром шутки. Без «минус участник», подсчёта банов,
прощаний с изгнанным, победных трофеев, оскорблений, угроз и унижения человека.
В самой реплике не обязательно называть бан: владельцу уже сообщат результат отдельно.
Ориентиры по настроению, не обязательные шаблоны:
«Модераторская совесть довольна. Премию принимаю мемами.»
«Разобралась. Самодовольства теперь на неделю.»
Придумывай собственные формулировки, меняй ритм и образ, не объясняй шутку.
Не зови возвращаться к разговору, продолжать общение или менять тему: ты не знаешь, шёл ли разговор.
Не добавляй финальное «Продолжаем», формальный отчёт, нравоучение или предложение помощи.
Не называй имён, не упоминай владельца, не выдумывай причины бана или тему разговора.
Не называй участника спамером или мошенником. Не утверждай, что весь чат очищен.
Никаких ссылок, упоминаний, разметки, описаний жестов или дополнительных пояснений.
Верни только готовую реплику.`,
          input: "Сформулируй реплику для чата после подтверждённого бана.",
          store: false,
          max_output_tokens: 1024,
        },
        { timeout: 10_000, maxRetries: 0 },
      );
      const text = response.output_text.trim();
      if (response.status !== "completed" || !text || [...text].length > 300) {
        throw new Error("Invalid ban announcement");
      }
      return text;
    } finally {
      active--;
    }
  };
}
